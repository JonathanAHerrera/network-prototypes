function inRing(lng: number, lat: number, ring: Ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** Bounding boxes so the grid scan skips ~95% of the polygon tests. */
const BOXES = LAND.map((ring) => {
  let x0 = 180;
  let x1 = -180;
  let y0 = 90;
  let y1 = -90;
  for (const [x, y] of ring) {
    if (x < x0) x0 = x;
    if (x > x1) x1 = x;
    if (y < y0) y0 = y;
    if (y > y1) y1 = y;
  }
  return { x0, x1, y0, y1 };
});

export interface LandDot {
  lng: number;
  lat: number;
}

let cache: LandDot[] | null = null;

/** 2°x2° dot grid over the land polygons. Computed once, then cached. */
export function landDots(): LandDot[] {
  if (cache) return cache;
  const dots: LandDot[] = [];
  for (let lat = -56; lat <= 80; lat += 2) {
    for (let lng = -180; lng < 180; lng += 2) {
      for (let k = 0; k < LAND.length; k++) {
        const b = BOXES[k];
        if (lng < b.x0 || lng > b.x1 || lat < b.y0 || lat > b.y1) continue;
        if (inRing(lng, lat, LAND[k])) {
          dots.push({ lng, lat });
          break;
        }
      }
    }
  }
  cache = dots;
  return dots;
}
